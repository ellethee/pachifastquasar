import { collectLocales, deepMerge } from '@ilpachi/pachi-i18n'
import type { PachiMessageMap } from '@ilpachi/pachi-i18n'
import it from './locales/it'
import en from './locales/en'

/**
 * Shell messages per language (`it` reference, `en`): namespaces `app`, `auth`, `menu`,
 * `dashboard`, `errors`, `common`. They are the base on which {@link composePachiMessages} layers the app messages.
 */
export const pachiShellMessages: PachiMessageMap = { it, en }

/** Reference schema of the shell messages (= Italian language). */
export type MessageSchema = typeof it

/** Message layers provided by the app: each is the result of `import.meta.glob(..., { eager: true, import: 'default' })`. */
export interface PachiMessageLayers {
  /** `src/i18n/generated/*.json`: generated by the backend (e.g. `errors.codes`), do not edit by hand. */
  generated?: Record<string, unknown>
  /** `src/i18n/overrides/*.{ts,json}`: customizations of the generated or shell texts. */
  overrides?: Record<string, unknown>
  /** `src/i18n/locales/*.ts`: app messages. */
  locales?: Record<string, unknown>
  /** `src/features/** /locales/*.ts`: feature messages. */
  features?: Record<string, unknown>
  /** Base languages (default {@link pachiShellMessages}). */
  base?: PachiMessageMap
}

/**
 * Composes the final messages per language. Increasing precedence (on the same key the later one wins,
 * deep merge): shell < generated < overrides < app locales < feature. The language code is the file
 * name (`it.ts`, `pt-BR.json`); adding a language = adding the `<code>.ts` files.
 *
 * @param layers - results of the app globs (see {@link PachiMessageLayers})
 * @returns `{ languageCode: messages }` to pass to `createPachiApp({ messages })`
 */
export function composePachiMessages(layers: PachiMessageLayers = {}): PachiMessageMap {
  const base = layers.base ?? pachiShellMessages
  const app = collectLocales({
    ...layers.generated,
    ...layers.overrides,
    ...layers.locales,
    ...layers.features
  })
  const result: PachiMessageMap = { ...base }
  for (const [code, messages] of Object.entries(app)) {
    result[code] = deepMerge(result[code] ?? {}, messages)
  }
  return result
}
